using KairuFocus.Domain.Community;
using KairuFocus.Domain.Identity;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace KairuFocus.Infrastructure.Persistence.Configurations;

/// <summary>
/// Maps <see cref="GroupSession"/>. The host stays in a private field (ADR-026): it is mapped by field
/// name and only serves joins with <c>MemberProfiles</c>.
/// </summary>
public sealed class GroupSessionConfiguration : IEntityTypeConfiguration<GroupSession>
{
    // The repository matches it against the SQL Server duplicate-key message to tell an id conflict from
    // any other failure, so a rename here must reach that check too. (Migrations keep their own literal:
    // a migration is a frozen snapshot of the schema at the time it was written.)
    internal const string PrimaryKeyName = "PK_GroupSessions";

    internal const string HostField = "_hostId";
    internal const string MembersField = "_members";

    public void Configure(EntityTypeBuilder<GroupSession> builder)
    {
        builder.ToTable("GroupSessions");

        builder.HasKey(g => g.Id)
            .HasName(PrimaryKeyName);

        // The EF constructor passes Guid.Empty: EF sets the real value (private setter) when it
        // materializes the row. The id is assigned by the domain, never generated by the database.
        // No foreign key to PomodoroSessions, like SharedSprintId: a group outlives the sessions of its members.
        builder.Property(g => g.Id)
            .HasColumnType("uniqueidentifier")
            .ValueGeneratedNever();

        builder.Property<UserId>(HostField)
            .HasColumnName("HostId")
            .HasConversion(id => id.Value, value => UserId.From(value))
            .HasColumnType("uniqueidentifier")
            .IsRequired();

        builder.HasIndex(HostField)
            .HasDatabaseName("IX_GroupSessions_HostId");

        builder.HasOne<User>()
            .WithMany()
            .HasForeignKey(HostField)
            .OnDelete(DeleteBehavior.Cascade);

        builder.OwnsOne(g => g.CurrentStep, step =>
        {
            step.Property(s => s.Number)
                .HasColumnName("CurrentStepNumber")
                .HasColumnType("int");

            step.Property(s => s.Type)
                .HasColumnName("CurrentStepType")
                .HasConversion<string>()
                .HasColumnType("nvarchar(20)")
                .HasMaxLength(20);

            step.Property(s => s.StartedAtUtc)
                .HasColumnName("CurrentStepStartedAtUtc")
                .HasColumnType("datetime2");

            step.Property(s => s.EndsAtUtc)
                .HasColumnName("CurrentStepEndsAtUtc")
                .HasColumnType("datetime2");
        });

        builder.Navigation(g => g.CurrentStep).IsRequired();

        builder.Property(g => g.SprintCount).HasColumnType("int");

        builder.Property(g => g.EndedAtUtc).HasColumnType("datetime2");

        // Longest value: "HostLeftCommunity" (17).
        builder.Property(g => g.EndReason)
            .HasConversion<string>()
            .HasColumnType("nvarchar(30)")
            .HasMaxLength(30);

        builder.Property(g => g.IsClosedToJoin)
            .HasColumnType("bit")
            .HasDefaultValue(false);

        // Bumped by the domain on writes of the group row only (never on Join / Leave), so two
        // simultaneous arrivals do not conflict while two host actions do.
        builder.Property(g => g.Version)
            .HasColumnType("int")
            .IsConcurrencyToken();

        builder.HasMany<GroupMember>(MembersField)
            .WithOne()
            .HasForeignKey("GroupSessionId")
            .OnDelete(DeleteBehavior.Cascade);

        builder.Ignore(g => g.ActiveMemberCount);
        builder.Ignore(g => g.DomainEvents);
    }
}

public sealed class GroupMemberConfiguration : IEntityTypeConfiguration<GroupMember>
{
    internal const string UserField = "_userId";

    public void Configure(EntityTypeBuilder<GroupMember> builder)
    {
        builder.ToTable("GroupSessionMembers");

        // No foreign key to Users on purpose: a second cascade path (Users -> GroupSessions -> members
        // and Users -> members) is refused by SQL Server. The rows of a deleted user stay until the
        // groups they belong to are deleted, and the read side ignores them (joins with MemberProfiles).
        builder.Property<UserId>(UserField)
            .HasColumnName("UserId")
            .HasConversion(id => id.Value, value => UserId.From(value))
            .HasColumnType("uniqueidentifier")
            .IsRequired();

        builder.Property<Guid>("GroupSessionId").HasColumnType("uniqueidentifier");

        builder.HasKey("GroupSessionId", UserField);

        builder.HasIndex(UserField)
            .HasDatabaseName("IX_GroupSessionMembers_UserId");

        builder.Property(m => m.JoinedAtUtc).HasColumnType("datetime2");
        builder.Property(m => m.LeftAtUtc).HasColumnType("datetime2");

        builder.Ignore(m => m.IsActive);
    }
}
